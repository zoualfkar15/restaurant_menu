function interpolate(str: string, params: Record<string, string>): string {
  let out = str;
  for (const [k, v] of Object.entries(params)) out = out.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
  return out;
}

export function translate(locale: Locale, key: string, params?: Record<string, string>): string {
  const entry = translations[key];
  if (!entry) return key;
  const raw = locale === 'ar' ? entry.ar : entry.en;
  return params ? interpolate(raw, params) : raw;
}
